"""Configuration and result data structures."""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from enum import Enum
from typing import TYPE_CHECKING

from .exceptions import ConfigurationError

if TYPE_CHECKING:  # pragma: no cover
    import pandas as pd

#: Refresh types accepted for partition-level refresh (TMSL / Enhanced Refresh API).
VALID_REFRESH_TYPES = frozenset(
    {"full", "automatic", "dataOnly", "calculate", "clearValues", "defragment"}
)
VALID_COMMIT_MODES = frozenset({"transactional", "partialBatch"})

_TIMEOUT_RE = re.compile(r"^\d{1,3}:[0-5]\d:[0-5]\d$")


class Strategy(str, Enum):
    """How the refresh is submitted to the service."""

    #: Try the Enhanced Refresh REST API; fall back to TMSL when the table has a
    #: refresh policy (the API refuses to target partitions of such tables).
    AUTO = "auto"
    #: Enhanced Refresh REST API only (asynchronous, polled).
    ENHANCED = "enhanced"
    #: TMSL ``refresh`` command through the XMLA endpoint (synchronous).
    TMSL = "tmsl"


@dataclass(frozen=True)
class PartitionSelector:
    """Selects the partitions of **one** table to refresh.

    All provided criteria are combined with AND.

    Attributes:
        table: Exact table name (case-insensitive).
        names: Explicit partition names (case-insensitive). ``None`` = no restriction.
        contains: Keep partitions whose name contains this text (case-insensitive).
        pattern: Keep partitions whose name matches this regular expression
            (``re.search``, case-insensitive).
        min_partition: Keep partitions whose name sorts ``>=`` this value.
        max_partition: Keep partitions whose name sorts ``<=`` this value.

    ``min_partition`` / ``max_partition`` compare names as strings. This is correct
    for the names generated by an incremental-refresh policy (``2025Q101``,
    ``2025Q204``, ``202511`` ...) because they sort chronologically.
    """

    table: str
    names: tuple[str, ...] | None = None
    contains: str | None = None
    pattern: str | None = None
    min_partition: str | None = None
    max_partition: str | None = None

    def __post_init__(self) -> None:
        if not self.table or not self.table.strip():
            raise ConfigurationError("PartitionSelector.table must be a non-empty table name.")
        if self.names is not None:
            object.__setattr__(self, "names", tuple(self.names))
        if self.pattern:
            try:
                re.compile(self.pattern)
            except re.error as exc:
                raise ConfigurationError(
                    f"Invalid partition regex {self.pattern!r}: {exc}"
                ) from exc
        if self.min_partition and self.max_partition and self.min_partition > self.max_partition:
            raise ConfigurationError(
                f"min_partition ({self.min_partition!r}) is greater than "
                f"max_partition ({self.max_partition!r})."
            )


@dataclass(frozen=True)
class RefreshOptions:
    """How the refresh is executed.

    Attributes:
        dry_run: When ``True`` (default) partitions are discovered and selected but
            **nothing is refreshed**. Set to ``False`` to actually refresh.
        strategy: See :class:`Strategy`.
        refresh_type: ``full`` is recommended for historic partitions.
        commit_mode: Enhanced API only. ``transactional`` is all-or-nothing.
        max_parallelism: Enhanced API only. Keep ``1`` for large historic partitions.
        retry_count: Enhanced API: passed to the service. TMSL: client-side retries
            of a failed batch.
        timeout: Enhanced API only, ``hh:mm:ss``.
        batch_size: Split the selected partitions into batches of this size and
            refresh them one after another. ``None`` = a single request.
            Smaller batches limit how much work is lost on failure.
        poll_interval_seconds: Enhanced API status polling interval.
        max_poll_minutes: Enhanced API polling window per batch.
        retry_delay_seconds: Wait between client-side TMSL retries.
        check_running_refresh: Refuse to start if the model already has a refresh in progress.
    """

    dry_run: bool = True
    strategy: Strategy = Strategy.AUTO
    refresh_type: str = "full"
    commit_mode: str = "transactional"
    max_parallelism: int = 1
    retry_count: int = 2
    timeout: str = "04:00:00"
    batch_size: int | None = None
    poll_interval_seconds: int = 30
    max_poll_minutes: int = 180
    retry_delay_seconds: int = 30
    check_running_refresh: bool = True

    def __post_init__(self) -> None:
        object.__setattr__(self, "strategy", Strategy(self.strategy))
        if self.refresh_type not in VALID_REFRESH_TYPES:
            raise ConfigurationError(
                f"refresh_type {self.refresh_type!r} is not valid. "
                f"Use one of: {sorted(VALID_REFRESH_TYPES)}"
            )
        if self.commit_mode not in VALID_COMMIT_MODES:
            raise ConfigurationError(
                f"commit_mode {self.commit_mode!r} is not valid. "
                f"Use one of: {sorted(VALID_COMMIT_MODES)}"
            )
        if self.max_parallelism < 1:
            raise ConfigurationError("max_parallelism must be >= 1.")
        if self.retry_count < 0:
            raise ConfigurationError("retry_count must be >= 0.")
        if not _TIMEOUT_RE.match(self.timeout):
            raise ConfigurationError(f"timeout must look like 'hh:mm:ss', got {self.timeout!r}.")
        if self.batch_size is not None and self.batch_size < 1:
            raise ConfigurationError("batch_size must be >= 1 or None.")
        if self.poll_interval_seconds < 1 or self.max_poll_minutes < 1:
            raise ConfigurationError("poll_interval_seconds and max_poll_minutes must be >= 1.")


@dataclass
class BatchResult:
    """Outcome of one submitted refresh request."""

    index: int
    partitions: list[str]
    strategy_used: str
    status: str  # Completed | Failed | Skipped
    started_utc: str | None = None
    finished_utc: str | None = None
    request_id: str | None = None
    attempts: int = 1
    error: str | None = None


@dataclass
class RefreshReport:
    """Everything that happened during :func:`refresh_partitions`."""

    workspace: str
    semantic_model: str
    table: str
    refresh_type: str
    dry_run: bool
    selected: pd.DataFrame
    batches: list[BatchResult] = field(default_factory=list)
    verification: pd.DataFrame | None = None

    @property
    def status(self) -> str:
        """``DryRun``, ``Completed``, ``Failed`` or ``PartiallyCompleted``."""
        if self.dry_run:
            return "DryRun"
        done = [b for b in self.batches if b.status == "Completed"]
        if not self.batches or len(done) == len(self.batches):
            return "Completed"
        return "PartiallyCompleted" if done else "Failed"

    @property
    def refreshed_partitions(self) -> list[str]:
        return [p for b in self.batches if b.status == "Completed" for p in b.partitions]

    def to_audit_frame(self) -> pd.DataFrame:
        """One row per partition with the outcome of the batch it belonged to."""
        import pandas as pd

        rows = []
        for b in self.batches:
            for p in b.partitions:
                rows.append(
                    {
                        "workspace": self.workspace,
                        "semantic_model": self.semantic_model,
                        "table": self.table,
                        "partition": p,
                        "refresh_type": self.refresh_type,
                        "batch": b.index,
                        "strategy": b.strategy_used,
                        "status": b.status,
                        "request_id": b.request_id,
                        "started_utc": b.started_utc,
                        "finished_utc": b.finished_utc,
                        "attempts": b.attempts,
                        "error": b.error,
                    }
                )
        return pd.DataFrame(rows)
